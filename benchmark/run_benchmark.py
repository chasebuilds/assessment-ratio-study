"""Score the detectors against the planted problems in the seeded synthetic county.

Runs many seeds and writes BENCHMARK.md. Every number comes from the run.
Usage: python benchmark/run_benchmark.py [n_seeds]
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

from assessment_ratio_study import pipeline, synth

CHECKS = {
    "regressive": ("Maple Hills", "PRB marginal or fail"),
    "low_median": ("Old Town", "median outside 0.90-1.10"),
    "high_cod": ("Riverbend", "COD above limit"),
    "sales_chasing": ("Ridgeview", "sales-chasing flag"),
}


def score(seed: int, trend: float = 0.0, adjust: str | None = None) -> dict[str, object]:
    df, truth = synth.generate(seed, trend)
    res = pipeline.run(df, time_adjust=adjust)
    st = res.strata.set_index("stratum")
    ex = res.screened.excluded.set_index("parcel_id")
    out: dict[str, object] = {}
    nb = st.loc["Maple Hills"]
    out["regressive"] = nb["prb_status"] in {"marginal", "fail"}
    out["regressive_strict"] = nb["prb_status"] == "fail"
    out["low_median"] = not bool(st.loc["Old Town", "median_ok"])
    rb = st.loc["Riverbend"]
    out["high_cod"] = not bool(rb["cod_ok"])
    out["high_cod_or_trim"] = (not bool(rb["cod_ok"])) or rb["verdict"] == "REVIEW"
    flagged = set(res.chasing.loc[res.chasing["flag"] == "SALES CHASING SUSPECTED", "group"])
    out["sales_chasing"] = "Ridgeview" in flagged
    out["ridgeview_ratio_verdict"] = st.loc["Ridgeview", "verdict"]
    clean_nb = [n for n in truth.clean_strata if n not in {"commercial", "vacant_land"}]
    clean = [st.loc[n, "verdict"] for n in clean_nb + ["commercial", "vacant_land"]]
    out["clean_total"] = len(clean)
    out["clean_fail"] = sum(v == "FAIL" for v in clean)
    out["clean_review"] = sum(v == "REVIEW" for v in clean)
    planted_nb = set(truth.planted)
    out["chasing_fp"] = len(
        flagged - {"Ridgeview", "all parcels"} - (planted_nb - {"Ridgeview"}) & set(clean_nb)
    )
    reasons = ex["reason"]
    out["flag_n"] = len(truth.flagged_non_arms)
    out["flag_caught"] = int((reasons.reindex(truth.flagged_non_arms) == "non_arms_length").sum())
    out["gross_n"] = len(truth.gross_errors)
    out["gross_caught"] = int(reasons.reindex(truth.gross_errors).notna().sum())
    out["subtle_n"] = len(truth.subtle_non_arms)
    out["subtle_caught"] = int(reasons.reindex(truth.subtle_non_arms).notna().sum())
    planted_ids = set(truth.flagged_non_arms) | set(truth.gross_errors) | set(truth.subtle_non_arms)
    legit = ex[ex["reason"].str.startswith("outlier") & ~ex.index.isin(planted_ids)]
    out["legit_trimmed"] = len(legit)
    out["valid_sales"] = len(res.screened.sales) + len(legit)
    out["est_pct"] = res.time_adjustment.annual_pct if res.time_adjustment else 0.0
    out["cod_clean_mean"] = float(st.loc[clean_nb, "cod"].mean())
    return out


def pct(x: float, n: float) -> str:
    return f"{100 * x / n:.1f}%"


def main() -> None:
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 30
    rows = pd.DataFrame([score(s) for s in range(1, n + 1)])
    s = rows.sum(numeric_only=True)
    trend = 0.12
    raw = pd.DataFrame([score(s, trend) for s in range(1, n + 1)])
    adj = pd.DataFrame([score(s, trend, "auto") for s in range(1, n + 1)])

    def tr(d: pd.DataFrame) -> list[str]:
        t_ = d.sum(numeric_only=True)
        return [
            f"{int(t_['regressive'])}/{n}",
            f"{int(t_['low_median'])}/{n}",
            f"{int(t_['sales_chasing'])}/{n}",
            f"{pct(t_['clean_fail'] + t_['clean_review'], t_['clean_total'])}",
            f"{d['cod_clean_mean'].mean():.2f}",
        ]

    ta_rows = [
        "## Rising market (12% a year, static roll)",
        "",
        f"Same {n} seeds, but sale prices drift up 12% over the year while assessments stay at "
        "their January values. Time adjustment (`--time-adjust auto`) estimates the trend and "
        "restates prices at the earliest sale date.",
        "",
        "| | Regressivity caught | Under-assessment caught | Sales chasing caught "
        "| FAIL or REVIEW on clean strata | Mean COD, clean neighborhoods |",
        "|---|---:|---:|---:|---:|---:|",
        "| No adjustment | " + " | ".join(tr(raw)) + " |",
        "| Auto time adjustment | " + " | ".join(tr(adj)) + " |",
        "",
        f"Estimated trend across seeds: mean {adj['est_pct'].mean():.1f}% a year "
        f"(range {adj['est_pct'].min():.1f}% to {adj['est_pct'].max():.1f}%) against 12.0% planted.",
        "",
    ]
    lines = (
        [
            "# Benchmark",
            "",
            f"Scored on {n} seeded synthetic counties (seeds 1 to {n}), about 840 sales each. "
            "Generated by `benchmark/run_benchmark.py`; the numbers below come from that run.",
            "",
            "## Planted problems (one per neighborhood, 8 residential neighborhoods per county)",
            "",
            "| Planted problem | Where | Detected by | Caught |",
            "|---|---|---|---:|",
            f"| Regressivity (ratio falls about 12% per doubling of price) | Maple Hills | PRB marginal or fail | {int(s['regressive'])}/{n} |",
            f"| Same, strict | Maple Hills | PRB beyond +/-0.10 | {int(s['regressive_strict'])}/{n} |",
            f"| Under-assessment (median ratio 0.80) | Old Town | median outside 0.90-1.10 | {int(s['low_median'])}/{n} |",
            f"| High dispersion (ratio spread 0.24 log sd) | Riverbend | COD above 15 | {int(s['high_cod'])}/{n} |",
            f"| Same, counting the trim-rate warning | Riverbend | COD above 15, or over 10% of sales trimmed | {int(s['high_cod_or_trim'])}/{n} |",
            f"| Sales chasing (only sold parcels reset to price) | Ridgeview | sold vs unsold flag | {int(s['sales_chasing'])}/{n} |",
            "",
            "**Finding: the Riverbend COD check misses every time.** The IQR trim runs per property "
            "class and cuts the wide tails of a high-dispersion neighborhood, so its COD after trimming "
            "lands under the limit. The report catches it only through the trim-rate warning (over 10% "
            "of the neighborhood's sales trimmed), which fires in the second row. A reviewer who looks "
            "only at COD would be fooled; read the trim rate next to it.",
            "",
            "Ridgeview's ratio table looks excellent (median about 1.00, COD about 2), so the ratio "
            f"statistics alone miss it. Ratio-table verdict was PASS in "
            f"{int((rows['ridgeview_ratio_verdict'] == 'PASS').sum())}/{n} counties.",
            "",
            "## False alarms on clean strata",
            "",
            f"Six clean strata per county (4 neighborhoods, commercial, vacant land), {int(s['clean_total'])} stratum-runs in all.",
            "",
            f"- FAIL on a clean stratum: {int(s['clean_fail'])} ({pct(s['clean_fail'], s['clean_total'])})",
            f"- REVIEW on a clean stratum: {int(s['clean_review'])} ({pct(s['clean_review'], s['clean_total'])})",
            f"- Sales-chasing flag on a clean neighborhood: {int(s['chasing_fp'])}",
            "",
            "## Sale validation screens",
            "",
            "| Planted sale problem | Caught | Share |",
            "|---|---:|---:|",
            f"| Flagged non-arm's-length (family, estate, foreclosure) | {int(s['flag_caught'])}/{int(s['flag_n'])} | {pct(s['flag_caught'], s['flag_n'])} |",
            f"| Unflagged typos, price 10x or 0.1x | {int(s['gross_caught'])}/{int(s['gross_n'])} | {pct(s['gross_caught'], s['gross_n'])} |",
            f"| Unflagged non-arm's-length at about half of market | {int(s['subtle_caught'])}/{int(s['subtle_n'])} | {pct(s['subtle_caught'], s['subtle_n'])} |",
            f"| Legitimate sales trimmed as outliers | {int(s['legit_trimmed'])}/{int(s['valid_sales'])} | {pct(s['legit_trimmed'], s['valid_sales'])} |",
            "",
        ]
        + ta_rows
        + [
            "## What this does not show",
            "",
            "- The data is synthetic and the planted effects are large on purpose. Smaller effects "
            "will be missed more often; a real roll has problems that are not planted here.",
            "- Detection depends on the stratum having at least 30 sales.",
            "- Results here say how the checks behave on this generator, not on any real county.",
            "",
        ]
    )
    Path("BENCHMARK.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
